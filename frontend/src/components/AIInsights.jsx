import { useEffect, useState } from "react";
import { AnimatePresence, motion } from "framer-motion";
import { Sparkles, Brain } from "lucide-react";
import { SectionHead } from "./Features";
import Robot3D from "./Robot3D";
import TiltCard from "./ui/TiltCard";

const INSIGHTS = [
  { tab: "Exam platform", tags: ["insight", "exam_workspace", "priority_high"], text: "Math completion is running 28% below the platform average. Question 8 shows a repeated hesitation pattern with a 42% reattempt rate. Recommended action: add a contextual hint and simplify the question prompt." },
  { tab: "E-commerce", tags: ["insight", "store_workspace", "priority_medium"], text: "Checkout abandonment rises 17% on mobile after the shipping step. Visitors who open the size guide are far more likely to return within 7 days. Recommended action: surface the size guide earlier and shorten the shipping form." },
  { tab: "SaaS", tags: ["insight", "saas_workspace", "priority_low"], text: "Users who finish onboarding in their first session show much higher 30-day retention. Recommended action: add a progress checklist and a day-2 reminder email." },
];
const chip = { priority_high: "bg-coral-soft text-coral-dark", priority_medium: "bg-amber-100 text-amber-600", priority_low: "bg-mint/60 text-[#0b6b58]" };

const Stream = ({ text }) => {
  const [n, setN] = useState(0);
  useEffect(() => { setN(0); const id = setInterval(() => setN((v) => (v >= text.length ? v : v + 2)), 18); return () => clearInterval(id); }, [text]);
  return <>{text.slice(0, n)}{n < text.length && <span className="inline-block w-[2px] h-4 bg-coral align-middle ml-0.5 animate-pulse" />}</>;
};

const AIInsights = () => {
  const [i, setI] = useState(0);
  const [hold, setHold] = useState(false);
  useEffect(() => { if (hold) return; const id = setInterval(() => setI((v) => (v + 1) % INSIGHTS.length), 9000); return () => clearInterval(id); }, [hold]);
  const cur = INSIGHTS[i];

  return (
    <section id="ai-insights" className="py-24 bg-white scroll-mt-24 relative overflow-hidden">
      <div className="container-x">
        <SectionHead eyebrow="AI insights" title="An analyst that explains the numbers" sub="Gemini reads your analytics and ML predictions, then tells you what is wrong and what to do next." />
        <div className="mt-14 grid lg:grid-cols-[0.8fr_1.2fr] gap-8 items-center">
          <motion.div initial={{ opacity: 0, scale: 0.9 }} whileInView={{ opacity: 1, scale: 1 }} viewport={{ once: true }} className="h-[360px] sm:h-[460px]">
            <Robot3D className="h-full" />
          </motion.div>

          <div onMouseEnter={() => setHold(true)} onMouseLeave={() => setHold(false)}>
            <div className="flex flex-wrap gap-2 mb-4">
              {INSIGHTS.map((t, k) => (
                <button key={t.tab} onClick={() => setI(k)} className={`px-4 py-2 rounded-full text-[13px] font-bold transition-all ${k === i ? "bg-ink text-white shadow-lg" : "bg-white border border-line text-ink-2 hover:border-coral/50 hover:text-coral"}`}>{t.tab}</button>
              ))}
            </div>
            <TiltCard max={3} className="glass rounded-3xl p-7 min-h-[260px]">
              <div className="flex items-center gap-2 text-[12px] font-bold text-coral-dark"><Sparkles className="w-4 h-4" />Generated by Gemini<Brain className="w-4 h-4 ml-auto text-muted" /></div>
              <AnimatePresence mode="wait">
                <motion.div key={i} initial={{ opacity: 0, y: 12 }} animate={{ opacity: 1, y: 0 }} exit={{ opacity: 0, y: -12 }} transition={{ duration: 0.3 }}>
                  <div className="mt-4 flex flex-wrap gap-2">
                    {cur.tags.map((t) => <span key={t} className={`px-2.5 py-1 rounded-lg text-[12px] font-bold font-mono ${chip[t] || "bg-slate-100 text-slate-600"}`}>{t}</span>)}
                  </div>
                  <p className="mt-4 text-[16.5px] leading-[1.75] text-ink-2 font-medium"><Stream text={cur.text} /></p>
                </motion.div>
              </AnimatePresence>
            </TiltCard>
            <p className="mt-3 text-xs text-muted">Sample insights for illustration</p>
          </div>
        </div>
      </div>
    </section>
  );
};
export default AIInsights;
